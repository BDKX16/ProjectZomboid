package io.github.bdkx16.regenerativeagriculture.guide;

import net.minecraft.advancements.AdvancementType;
import net.minecraft.resources.Identifier;
import net.minecraft.world.item.Item;
import io.github.bdkx16.regenerativeagriculture.RegenerativeAgriculture;
import io.github.bdkx16.regenerativeagriculture.registry.ModBlocks;
import io.github.bdkx16.regenerativeagriculture.registry.ModCrops;
import io.github.bdkx16.regenerativeagriculture.registry.ModFoods;
import io.github.bdkx16.regenerativeagriculture.registry.ModItems;

import java.util.List;
import java.util.Optional;
import java.util.function.Supplier;

/**
 * The mod's route: a tree of milestones shown as linked nodes in the manual. Each node is a real advancement
 * ({@code regenerative_agriculture:route/<id>}, generated by datagen), so progress is saved and synced by the game and the
 * route also shows up in the vanilla advancements screen.
 */
public final class RouteNodes {

    /**
     * @param parents nodes it hangs from (the first one is the advancement's parent); empty for the root
     * @param x       column on the map
     * @param y       row on the map
     */
    public record Node(String id, Supplier<Item> icon, List<String> parents, int x, int y, AdvancementType type) {
        public Identifier advancement() {
            return RegenerativeAgriculture.id("route/" + id);
        }

        public String titleKey() {
            return "route." + RegenerativeAgriculture.MOD_ID + "." + id;
        }

        public String descriptionKey() {
            return titleKey() + ".desc";
        }
    }

    public static final List<Node> ALL = List.of(
            node("wild_seeds", () -> ModCrops.TOMATO.seeds(), 0, 4, AdvancementType.TASK),
            node("first_harvest", () -> ModCrops.LETTUCE.produce(), 2, 2, AdvancementType.TASK, "wild_seeds"),
            node("pruning_shears", () -> ModItems.PRUNING_SHEARS, 4, 0, AdvancementType.TASK, "first_harvest"),
            node("soil_test", () -> ModItems.SOIL_TEST_KIT, 4, 1, AdvancementType.TASK, "first_harvest"),
            node("compost", () -> ModItems.COMPOST, 6, 0, AdvancementType.TASK, "soil_test"),
            node("mulch", () -> ModItems.STRAW_MULCH, 6, 1, AdvancementType.TASK, "soil_test"),
            node("salad", () -> ModFoods.GREEN_SALAD.item(), 4, 2, AdvancementType.TASK, "first_harvest"),
            node("hamburger", () -> ModFoods.HAMBURGER.item(), 6, 2, AdvancementType.TASK, "salad"),
            node("nourished", () -> ModFoods.LOCRO.item(), 8, 2, AdvancementType.GOAL, "hamburger"),
            node("drying_rack", () -> ModBlocks.DRYING_RACK.asItem(), 4, 4, AdvancementType.TASK, "first_harvest"),
            node("dried", () -> ModItems.DRIED_TOBACCO, 6, 4, AdvancementType.TASK, "drying_rack"),
            node("cured", () -> ModItems.CURED_TOBACCO, 8, 3, AdvancementType.GOAL, "dried"),
            node("mate", () -> ModItems.MATE, 8, 4, AdvancementType.TASK, "dried"),
            node("thermos", () -> ModItems.THERMOS_HOT, 10, 4, AdvancementType.GOAL, "mate"),
            node("malt", () -> ModItems.MALT, 8, 5, AdvancementType.TASK, "dried"),
            node("brewery", () -> ModBlocks.FERMENTER.asItem(), 10, 5, AdvancementType.TASK, "malt"),
            node("beer", () -> ModFoods.BEER.item(), 12, 5, AdvancementType.CHALLENGE, "brewery"),
            node("weather_station", () -> ModBlocks.WEATHER_STATION.asItem(), 2, 7, AdvancementType.TASK, "wild_seeds"),
            node("thermohygrometer", () -> ModItems.THERMOHYGROMETER, 4, 7, AdvancementType.TASK, "weather_station"),
            node("greenhouse", () -> net.minecraft.world.item.Items.GLASS, 6, 6, AdvancementType.GOAL, "thermohygrometer"),
            node("extractor", () -> ModBlocks.EXTRACTOR.asItem(), 6, 7, AdvancementType.TASK, "thermohygrometer"),
            node("grow_light", () -> ModBlocks.GROW_LIGHT.asItem(), 6, 8, AdvancementType.TASK, "thermohygrometer"),
            node("grow_room", () -> ModCrops.BASIL.produce(), 8, 8, AdvancementType.GOAL, "grow_light", "extractor"));

    private RouteNodes() {
    }

    public static Node root() {
        return ALL.getFirst();
    }

    public static Optional<Node> byId(String id) {
        return ALL.stream().filter(node -> node.id().equals(id)).findFirst();
    }

    private static Node node(String id, Supplier<Item> icon, int x, int y, AdvancementType type, String... parents) {
        return new Node(id, icon, List.of(parents), x, y, type);
    }
}
